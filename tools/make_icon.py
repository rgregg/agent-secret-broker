"""Regenerate every rendered copy of the ASB logo from assets/logo/*.svg.

Needs rsvg-convert (librsvg) and Pillow; run from the repo root: python3 tools/make_icon.py

Writes:
  secret_broker/icon.py                                  180x180 home-screen icon (apple-touch-icon), from logo-square.svg
  macos/ASBApprover/Resources/Assets.xcassets/AppIcon.appiconset/   the Mac app icon (also what its banners show), from logo.svg
  macos/ASBApprover/Resources/Assets.xcassets/MenuBarIcon.imageset/ the 18 pt menu bar template image, from glyph.svg

The dashboard favicon (_ICON in secret_broker/broker.py) is a small inline SVG copy of logo-square.svg,
edited by hand.
"""
import base64
import io
import json
import os
import subprocess
import tempfile

from PIL import Image

LOGO = "assets/logo"
ASSETS = "macos/ASBApprover/Resources/Assets.xcassets"
# (points, scale) pairs macOS wants in an app icon set.
MAC_ICON = [(16, 1), (16, 2), (32, 1), (32, 2), (128, 1), (128, 2), (256, 1), (256, 2), (512, 1), (512, 2)]


def render(svg, px):
    """The SVG rendered to a px-by-px RGBA image."""
    with tempfile.TemporaryDirectory() as d:
        out = os.path.join(d, "out.png")
        subprocess.run(["rsvg-convert", "-w", str(px), "-h", str(px), "-o", out, svg], check=True)
        return Image.open(out).convert("RGBA")


def png_bytes(img, **kw):
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True, **kw)
    return buf.getvalue()


def write_json(path, obj):
    with open(path, "w") as f:
        json.dump(obj, f, indent=2)
        f.write("\n")


def home_screen_icon():
    # Opaque and palette-quantized: the bytes are inlined into every page, so keep them small.
    img = render(f"{LOGO}/logo-square.svg", 180).convert("RGB").quantize(colors=128, dither=Image.Dither.NONE)
    raw = png_bytes(img)
    b64 = base64.b64encode(raw).decode()
    with open("secret_broker/icon.py", "w") as f:
        f.write('"""Generated by tools/make_icon.py: 180x180 PNG home-screen icon (apple-touch-icon)."""\n'
                "import base64\n\nPNG = base64.b64decode(\n")
        for i in range(0, len(b64), 76):
            f.write(f'    "{b64[i:i + 76]}"\n')
        f.write(")\n")
    print("secret_broker/icon.py:", len(raw), "bytes")


def mac_app_icon():
    d = f"{ASSETS}/AppIcon.appiconset"
    os.makedirs(d, exist_ok=True)
    images = []
    for pt, scale in MAC_ICON:
        name = f"icon_{pt}x{pt}{'@2x' if scale == 2 else ''}.png"
        with open(f"{d}/{name}", "wb") as f:
            f.write(png_bytes(render(f"{LOGO}/logo.svg", pt * scale)))
        images.append({"filename": name, "idiom": "mac", "scale": f"{scale}x", "size": f"{pt}x{pt}"})
    write_json(f"{d}/Contents.json", {"images": images, "info": {"author": "xcode", "version": 1}})
    print(d + ":", len(images), "images")


def menu_bar_glyph():
    d = f"{ASSETS}/MenuBarIcon.imageset"
    os.makedirs(d, exist_ok=True)
    for name, px in (("MenuBarIcon.png", 18), ("MenuBarIcon@2x.png", 36)):
        with open(f"{d}/{name}", "wb") as f:
            f.write(png_bytes(render(f"{LOGO}/glyph.svg", px)))
    write_json(f"{d}/Contents.json", {
        "images": [{"filename": "MenuBarIcon.png", "idiom": "mac", "scale": "1x"},
                   {"filename": "MenuBarIcon@2x.png", "idiom": "mac", "scale": "2x"}],
        "info": {"author": "xcode", "version": 1},
        "properties": {"template-rendering-intent": "template"},
    })
    print(d + ": 2 images")


if __name__ == "__main__":
    home_screen_icon()
    mac_app_icon()
    menu_bar_glyph()
