"""Regenerate secret_broker/icon.py (the 180x180 home-screen icon).

Needs Pillow; run from the repo root: python3 tools/make_icon.py
The icon is the same blue "A" tile as the inline SVG favicon, drawn full-bleed
because iOS applies its own rounded mask.
"""
import base64
import io

from PIL import Image, ImageDraw, ImageFont

S = 180
img = Image.new("RGB", (S, S), "#2563eb")
d = ImageDraw.Draw(img)
font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 118)
d.text((S / 2, S / 2 + 4), "A", font=font, fill="white", anchor="mm")
buf = io.BytesIO()
img.save(buf, "PNG", optimize=True)
b64 = base64.b64encode(buf.getvalue()).decode()
lines = [b64[i:i + 76] for i in range(0, len(b64), 76)]
with open("secret_broker/icon.py", "w") as f:
    f.write('"""Generated by tools/make_icon.py: 180x180 PNG home-screen icon (apple-touch-icon)."""\n'
            "import base64\n\nPNG = base64.b64decode(\n")
    for ln in lines:
        f.write(f'    "{ln}"\n')
    f.write(")\n")
print(len(buf.getvalue()), "bytes")
