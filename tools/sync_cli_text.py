#!/usr/bin/env python3
"""Keep the Rust CLI's help and guide text identical to the Python CLI's.

While both CLIs exist, client/asb is the source of truth for every word of `asb --help`, `asb guide` and
`asb help COMMAND`. This extracts them into crates/asb-cli/text/ (embedded by the Rust binary with include_str!) and
writes crates/asb-cli/src/text_gen.rs. tests/test_cli_text_sync.py fails if the committed files differ from what this
would write, so editing the Python text without running this cannot go unnoticed.

    python tools/sync_cli_text.py            # rewrite the files
    python tools/sync_cli_text.py --check    # exit 1 if they are out of date
"""
import importlib.machinery
import importlib.util
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "crates", "asb-cli")


def load_python_cli():
    loader = importlib.machinery.SourceFileLoader("asb_text_source", os.path.join(ROOT, "client", "asb"))
    mod = importlib.util.module_from_spec(importlib.util.spec_from_loader("asb_text_source", loader))
    loader.exec_module(mod)
    return mod


def generate():
    """{relative path: file content} for everything this tool owns."""
    cli = load_python_cli()
    files = {"text/doc.txt": cli.__doc__, "text/guide.txt": cli.GUIDE}
    for name, text in cli.HELP.items():
        files[f"text/help/{name}.txt"] = text
    arms = "\n".join(f'        "{name}" => Some(include_str!("../text/help/{name}.txt")),' for name in cli.HELP)
    order = ", ".join(f'"{name}"' for name in cli.HELP)
    files["src/text_gen.rs"] = f'''// GENERATED by tools/sync_cli_text.py from client/asb. Do not edit: change the Python text and re-run the tool.

/// What `asb` and `asb --help` print.
pub const DOC: &str = include_str!("../text/doc.txt");

/// What `asb guide` prints.
pub const GUIDE: &str = include_str!("../text/guide.txt");

/// The commands that have `asb help COMMAND` text, in the order the Python CLI lists them.
pub const HELP_TOPICS: &[&str] = &[{order}];

/// The text of `asb help COMMAND`.
pub fn help(topic: &str) -> Option<&'static str> {{
    match topic {{
{arms}
        _ => None,
    }}
}}
'''
    return files


def main():
    files = generate()
    check = "--check" in sys.argv[1:]
    stale = []
    for rel, content in files.items():
        path = os.path.join(OUT, rel)
        try:
            with open(path, encoding="utf-8", newline="") as f:
                same = f.read() == content
        except OSError:
            same = False
        if not same:
            stale.append(rel)
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="") as f:
                    f.write(content)
    if check and stale:
        print("out of date (run tools/sync_cli_text.py): " + ", ".join(stale))
        sys.exit(1)
    print(("checked" if check else "wrote") + f" {len(files)} files" + (f" ({len(stale)} changed)" if stale and not check else ""))


if __name__ == "__main__":
    main()
